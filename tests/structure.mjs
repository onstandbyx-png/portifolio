import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const r = path=>readFileSync(new URL(path,import.meta.url),'utf8');
const h=r('../index.html'),css=r('../src/styles.css'),js=r('../src/portfolio.js');
for(const id of ['inicio','trabalhos','categorias','editorial','experiencias','laboratorio','sistemas','contato','case-dialog','reading-progress']) assert(h.includes(`id="${id}"`),`Seção não encontrada: ${id}`);
assert.equal((h.match(/data-category-index="/g)||[]).length,4,'Esperados quatro cartões');
assert.equal((h.match(/data-ad-tab="/g)||[]).length,4,'Esperados quatro canais');
assert.equal((h.match(/data-story-step="/g)||[]).length,3,'Esperados três capítulos editoriais');
assert.equal((h.match(/data-case="/g)||[]).length,3,'Esperados três casos');
assert.equal((h.match(/data-system-step="/g)||[]).length,4,'Esperadas quatro etapas CI');
assert(h.includes('/assets/fatos-cover-detail.webp'),'Asset original Fatos indisponível');
assert(h.includes('smiile-landing-preview.up.railway.app'),'Falta referência smiile');
assert(h.includes('midia-kit-production-c234.up.railway.app'),'Falta referência Fatos');
assert(css.includes('prefers-reduced-motion'),'Acessibilidade de movimento ausente');
assert(js.includes('requestAnimationFrame')&&js.includes('category-runway'),'Scroll nativo ausente');
assert(js.includes('showModal()'),'Modal nativo ausente');
assert(js.includes('navigator.clipboard.writeText'),'Preparação de briefing ausente');
assert(!/\b(?:\d{2,})\s*(?:%|leads|ROAS)\b/i.test(h),'Possível métrica fictícia');
console.log('PASS: estrutura, assets, acessibilidade, controles e proveniência');